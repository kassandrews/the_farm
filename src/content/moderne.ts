// Set Two: Moderne — the mid-century set. The first set authored against Set
// One's standard, and the first proof that the lattice's promise (DESIGN §The
// catalog) can be kept twice.
//
// WHAT A SET MAY OWN IS THE SILHOUETTE, and mid-century turns out to be the
// style that proves the doctrine right: a credenza is not mid-century because
// it is walnut — the finish stays the player's — it is mid-century because of
// what the outline does. Four moves, applied everywhere:
//
//   1. LEGS, NOT PLINTHS. Set One's casework stands on plinths that run to the
//      floor; Moderne lifts every carcass onto tapered legs with daylight
//      underneath. This one move is most of the style.
//   2. SEATS SPLAY, SURFACES STAND STRAIGHT (owner's rule, fourth sitting: a
//      table's job is to hold still). A seat's leg is three pixels at the
//      frame and two at the floor, stepping outward as it goes; a surface's
//      leg drops plumb — which also keeps a carrier's feet inside the carcass
//      line, since `surfaceBand()` reads the widest drawn row as the surface
//      (render/furnishings.ts).
//   3. LOW AND LONG. Backs drop, seats thin, tops lose a row. The air the
//      silhouette gives up at the top it gets back underneath.
//   4. THE FLOAT. Where Set One joins two masses with a rule, Moderne prefers a
//      gap — the chair's back hovers over its seat on the rear stiles alone.
//
// Everything else is inherited law: `c`/`t`/`s` ask the finish, capitals ask
// the trim, `k` is the shared ink, shared parts are drawn once and spread
// (§CHAIR_BACK's argument, one file over), and a footprint is what a piece MAY
// occupy, never what it must fill.
//
// PILOT PIECES FIRST (owner's call, 18 Aug 2026): sofa, dresser, lamp, chair —
// front views only, to settle the style's grammar on four silhouettes before
// the other twenty-five forms are drawn to it. Until the set covers every
// form, `sets.test.ts` fails on the holes BY DESIGN — the red tests are the
// authoring checklist, and the set does not ship until they are the proof of
// completeness instead.
//
// OWED BEFORE SHIP, found while wiring the pilots: `lampLift()` in renderer.ts
// keys on the piece ID, but mid-cell standing is a fact about the PROCEDURAL
// lamp drawing, which core's is and this set's is not — a grid-drawn lamp
// stands on the near edge like the rest of the catalogue, so the glow's lift
// has to learn to ask the set. Invisible on the midday sheet; wrong after dark.

